import { asRecord } from "./values.js";
import {
  available,
  count,
  counts,
  flag,
  interval,
  labels,
  metric,
  probability,
  rows,
  strand,
  text,
} from "./contextValues.js";

export function normalizeProphageContext(value) {
  const doc = asRecord(value) || {};
  return {
    available: available(doc),
    searchPolicy: {
      scope: text(doc.search_policy?.scope),
      queryCategories: labels(doc.search_policy?.query_categories, 5),
      queryAlphabet: text(doc.search_policy?.query_alphabet),
      minLength: count(doc.search_policy?.min_query_length),
      maxLength: count(doc.search_policy?.max_query_length),
      method: text(doc.search_policy?.method),
      arrayExclusion: text(doc.search_policy?.array_exclusion),
      complete: flag(doc.search_policy?.search_complete),
      truncated: flag(doc.search_policy?.results_truncated),
      pam: text(doc.search_policy?.pam),
      targetingActivity: text(doc.search_policy?.targeting_activity),
    },
    counts: counts(doc.counts, [
      "sources",
      "assessed_sources",
      "regions",
      "genes",
      "spacer_matches",
    ]),
    sources: rows(doc.sources, 20).map((row) => ({
      id: text(row.id),
      length: count(row.length),
      status: ["assessed", "ineligible_short_sequence"].includes(row.status) ? row.status : null,
    })),
    sourceArrays: rows(doc.source_arrays).map((row) => ({
      id: text(row.id),
      nativeId: text(row.native_id),
      sourceId: text(row.source_id),
      ...interval(row),
      category: text(row.category),
      orientation: strand(row.orientation),
    })),
    sourceSpacers: rows(doc.source_spacers).map((row) => ({
      id: text(row.id),
      arrayId: text(row.array_id),
      sourceId: text(row.source_id),
      ordinal: count(row.ordinal),
      ...interval(row),
      sequence: text(row.sequence),
      status: text(row.status),
      boundary: count(row.boundary),
    })),
    sourceInventoryComplete: doc.source_inventory_complete === true,
    regions: rows(doc.regions).map((row) => ({
      id: text(row.id),
      sourceId: text(row.source_id),
      ...interval(row),
      geneIds: labels(row.gene_ids),
      supportingGeneIds: labels(row.supporting_gene_ids),
      leftEdge: flag(row.first_gene_at_record_edge),
      rightEdge: flag(row.last_gene_at_record_edge),
      peakScore: metric(row.peak_score),
    })),
    matches: rows(doc.spacer_matches).map((row) => ({
      queryId: text(row.query_id),
      sourceId: text(row.source_id),
      arrayId: text(row.array_id),
      spacerIndex: count(row.spacer_index),
      targetSourceId: text(row.target_source_id),
      ...interval(row),
      strand: row.strand === "both" ? "both" : strand(row.strand),
      regionIds: labels(row.region_ids),
      identity: probability(row.identity),
      matchClass: row.match_class === "sequence_match" ? "sequence_match" : null,
    })),
    regionsTruncated: doc.regions_truncated === true,
    matchesTruncated: doc.spacer_matches_truncated === true,
  };
}
